const {chromium}=require('playwright');
const fs=require('node:fs');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||'/usr/bin/chromium',args:['--no-sandbox']});
 for(const screen of [{w:1440,h:900},{w:1024,h:768},{w:820,h:1100},{w:390,h:844}]){
  const page=await browser.newPage({viewport:{width:screen.w,height:screen.h},acceptDownloads:true,hasTouch:screen.w<1024});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:8080/');
  await page.locator('#book').click();
  await page.getByRole('button',{name:'Panduan PdP'}).click();
  const text=await page.locator('#bookPages').innerText();
  assert.match(text,/SP 7.1.1/);assert.match(text,/SP 7.1.2/);assert.match(text,/60 Minit/);
  await page.locator('.book-glossary summary').click();
  assert.match(await page.locator('.book-glossary').innerText(),/Partikel kapilari/);
  await page.getByRole('button',{name:'Rubrik PBD'}).click();
  await page.locator('#pbdStudentName').fill('Murid Ujian');
  await page.locator('[data-score="7.1.1"]').selectOption('2');
  await page.locator('#pbdComment').fill('Mengaplikasi pemerhatian secara lisan.');
  await page.locator('#saveRubric').click();
  const downloadPromise=page.waitForEvent('download');
  await page.locator('#exportPBD').click();
  const downloaded=await downloadPromise;
  assert.match(downloaded.suggestedFilename(),/ringkasan-pbd/);
  const csv=fs.readFileSync(await downloaded.path(),'utf8');
  assert.match(csv,/Nama Murid/);assert.match(csv,/Murid Ujian/);
  assert.match(csv,/2/);
  await page.locator('#close').click();
  await page.locator('#settings').click();
  await page.locator('#mode').selectOption('kelas');
  await page.getByRole('button',{name:'Pilih Misi / Main Semula'}).click();
  await page.getByRole('button',{name:'Misi 3 · Makmal Tani Pintar'}).click();
  const part=page.locator('[data-part="level"]');
  await part.click();
  await page.locator('[data-target="inlet"]').click();
  assert.equal(await page.locator('.parts-tray .selected').count(),0,'Wrong drop resets selection');
  assert.match(await page.locator('#assemblyFeedback').innerText(),/Belum tepat/);
  await part.click();
  await page.locator('[data-target="level"]').click();
  assert.equal(await page.locator('[data-part="level"]').isDisabled(),true);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,'No horizontal layout overflow');
  assert.deepEqual(errors,[],'No runtime page exceptions');
  await page.close();
 }
 const recovery=await browser.newPage();
 await recovery.addInitScript(()=>{localStorage.setItem('misi-bandar-v2','{not-json')});
 await recovery.goto('http://127.0.0.1:8080/');
 assert.equal(await recovery.evaluate(()=>localStorage.getItem('misi-bandar-v2-recovery')),'{not-json');
 assert.equal(await recovery.locator('#home').isVisible(),true);
 await recovery.close();
 await browser.close();
 console.log('PASS: RPH lesson checklist/glossary, pupil PBD CSV export, wrong-drop recovery, 4 viewport layouts and malformed save preservation');
})().catch(e=>{console.error(e);process.exit(1)});
