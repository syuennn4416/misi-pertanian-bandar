const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||'/usr/bin/chromium',args:['--no-sandbox']});
 for(const [device,width,height] of [['desktop',1440,900],['tablet',820,1100],['phone',390,844]]){
  const page=await browser.newPage({viewport:{width,height},hasTouch:device!=='desktop',acceptDownloads:true});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:8080/');
  await page.locator('#dialogToggle').click();
  assert.equal(await page.locator('#dialogueTranscript').isVisible(),true,'Full Alya text is in task rail');
  assert.match(await page.locator('#transcriptText').innerText(),/Alya|ruang rumah/i);
  const stage=await page.locator('#stage').boundingBox(), transcript=await page.locator('#dialogueTranscript').boundingBox();
  if(width>780)assert.ok(transcript.x>=stage.x+stage.width-2,'Transcript never covers play canvas');
  else assert.ok(transcript.y>=stage.y+stage.height-2,'Phone transcript is stacked under game canvas');
  await page.locator('#transcriptPause').click();
  await page.locator('#transcriptClose').click();
  assert.equal(await page.locator('#dialogueTranscript').isVisible(),false);
  await page.locator('#settings').click();
  await page.locator('#voicePitch').evaluate(el=>{el.value='1.15';el.dispatchEvent(new Event('input',{bubbles:true}))});
  await page.locator('#refreshVoices').click();
  await page.locator('#deviceCheck').click();
  assert.match(await page.locator('.device-results').innerText(),/HTTPS|API kamera/);
  assert.equal(await page.locator('#checkCameraPermission').isDisabled(),false);
  await page.locator('#backToSettings').click();
  assert.equal(await page.locator('#voicePitch').inputValue(),'1.15');
  await page.locator('#close').click();
  await page.locator('#book').click();
  await page.getByRole('button',{name:'Rubrik PBD'}).click();
  await page.locator('#pbdStudentName').fill('Murid Contoh');
  await page.locator('[data-score="7.1.1"]').selectOption('2');
  await page.locator('#saveRubric').click();
  await page.locator('#viewReport').click();
  assert.match(await page.locator('#printContent').innerText(),/Murid Contoh/);
  await page.locator('#close').click();
  await page.locator('#book').click();
  const promise=page.waitForEvent('download');await page.locator('#backup').click();const download=await promise;
  assert.match(download.suggestedFilename(),/sandaran-misi-pertanian/);
  const backup=await page.evaluate(()=>JSON.parse(localStorage.getItem('misi-bandar-v2')));
  const payload={product:'misi-pertanian-bandar',format:1,mode:backup.mode,profiles:backup.profiles};
  await page.locator('#backupFile').setInputFiles({name:'sandaran.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(payload))});
  await page.locator('#confirmImport').waitFor({state:'visible',timeout:5000});
  assert.match(await page.locator('#modalBody').innerText(),/Sahkan Import Sandaran/);
  await page.locator('#cancelImport').click();
  await page.locator('#book').click();
  await page.locator('#backupFile').setInputFiles({name:'sandaran.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(payload))});
  await page.locator('#confirmImport').click();
  await page.locator('#book').click();
  await page.getByRole('button',{name:'Rubrik PBD'}).click();
  assert.equal(await page.locator('#pbdStudentName').inputValue(),'Murid Contoh');
  assert.equal(await page.locator('[data-score="7.1.1"]').inputValue(),'2');
  await page.locator('#close').click();
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  assert.deepEqual(errors,[]);
  await page.close();
 }
 await browser.close();
 console.log('PASS: device inspector, pitch controls, full Alya sidebar transcript, safe import confirmation, manual PBD learner name and responsive layout');
})().catch(e=>{console.error(e);process.exit(1)});
